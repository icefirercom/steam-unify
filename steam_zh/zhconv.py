_TRANS_TABLE = str.maketrans({t: s for t, s in _CHAR_PAIRS if t != s})


def to_simplified(text: str) -> str:
    """Convert Traditional Chinese text (especially game titles) to Simplified Chinese."""
    if not text:
        return ""
    out = str(text)
    for trad, simp in _PHRASES:
        if trad in out:
            out = out.replace(trad, simp)
    return out.translate(_TRANS_TABLE)
